    private sealed class RazorSimulatingGenerator : IIncrementalGenerator
    {
        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            var texts = context.AdditionalTextsProvider.Where(static text => text.Path.EndsWith(".razor", StringComparison.OrdinalIgnoreCase));
            context.RegisterSourceOutput(texts, static (spc, text) =>
            {
                var content = text.GetText()?.ToString() ?? "";
                var fileName = Path.GetFileName(text.Path.Replace('\\', '/'));
                // Simulate Razor generator emitting #line directive pointing back to .razor file
                var generatedSource = $$"""
                    // <auto-generated/>
                    public class {{Path.GetFileNameWithoutExtension(fileName)}}Component
                    {
                        public void BuildRenderTree()
                        {
                    #line (3, 9)-(3, 23) "{{text.Path}}"
                            TargetMethod();
                    #line default
                        }

                        public void TargetMethod() {}
                    }
                    """;
                spc.AddSource($"{fileName}.g.cs", generatedSource);
            });
        }
    }

    private sealed class InMemoryAdditionalText : AdditionalText
    {
        private readonly string _path;
        private readonly SourceText _text;
        public InMemoryAdditionalText(string path, string text)
        {
            _path = path;
            _text = SourceText.From(text);
        }
        public override string Path => _path;
        public override SourceText GetText(CancellationToken cancellationToken = default) => _text;
    }

    [Fact]
    public async Task TestGeneratorWithMappedLineSpanResolvesToRazorFile()
    {
        var razorPath = Path.Combine(Path.GetTempPath(), "Counter.razor");
        var razorContent = "@code {\n    // line 2\n    TargetMethod();\n}";
        var additionalText = new InMemoryAdditionalText(razorPath, razorContent);

        var comp = CSharpCompilation.Create("TestProj",
            references: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]);

        var gen = new RazorSimulatingGenerator().AsSourceGenerator();
        var driver = CSharpGeneratorDriver.Create(
            generators: [gen],
            additionalTexts: [additionalText],
            parseOptions: new CSharpParseOptions(LanguageVersion.Latest));

        driver.RunGeneratorsAndUpdateCompilation(comp, out var outputComp, out var diagnostics);

        var generatedTree = outputComp.SyntaxTrees.FirstOrDefault(t => t.FilePath.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase));
        generatedTree.Should().NotBeNull();

        var root = await generatedTree!.GetRootAsync();
        var invocation = root.DescendantNodes().OfType<Microsoft.CodeAnalysis.CSharp.Syntax.InvocationExpressionSyntax>().First();

        var mappedSpan = invocation.GetLocation().GetMappedLineSpan();
        mappedSpan.HasMappedPath.Should().BeTrue();
        mappedSpan.Path.Should().Be(razorPath);
        // StartLinePosition.Line is 0-indexed (line 3 is index 2)
        mappedSpan.StartLinePosition.Line.Should().Be(2);
        // StartLinePosition.Character is 0-indexed (line directive col 9 + 8 spaces indentation = 16)
        mappedSpan.StartLinePosition.Character.Should().Be(16);
    }

    [Fact]
    public async Task TestSymbolFinderFindsReferencesInGeneratedCode()
    {
        using var workspace = new AdhocWorkspace();
        var projInfo = ProjectInfo.Create(
            ProjectId.CreateNewId(),
            VersionStamp.Create(),
            "SampleLib",
            "SampleLib",
            LanguageNames.CSharp,
            metadataReferences: [MetadataReference.CreateFromFile(typeof(object).Assembly.Location)]);

        var solution = workspace.CurrentSolution.AddProject(projInfo);

        var docInfo = DocumentInfo.Create(
            DocumentId.CreateNewId(projInfo.Id),
            "Service.cs",
            loader: TextLoader.From(TextAndVersion.Create(
                SourceText.From("""
                    public class Service
                    {
                        public void TargetMethod() {}
                    }
                    """), VersionStamp.Create())));

        solution = solution.AddDocument(docInfo);

        // Add a document simulating generated code with #line directive
        var genDocInfo = DocumentInfo.Create(
            DocumentId.CreateNewId(projInfo.Id),
            "Component.razor.g.cs",
            filePath: @"C:\Repo\obj\Debug\net10.0\Component.razor.g.cs",
            loader: TextLoader.From(TextAndVersion.Create(
                SourceText.From("""
                    public class Component
                    {
                        public void Execute(Service s)
                        {
                    #line (5, 9)-(5, 23) "C:\Repo\Pages\Component.razor"
                            s.TargetMethod();
                    #line default
                        }
                    }
                    """), VersionStamp.Create())));

        solution = solution.AddDocument(genDocInfo);

        var project = solution.GetProject(projInfo.Id)!;
        var comp = await project.GetCompilationAsync();
        comp.Should().NotBeNull();

        var serviceType = comp!.GetTypeByMetadataName("Service")!;
        var targetMethod = serviceType.GetMembers("TargetMethod").First();

        var refs = (await Microsoft.CodeAnalysis.FindSymbols.SymbolFinder.FindReferencesAsync(targetMethod, solution)).ToList();

        refs.Should().NotBeEmpty();
        var allLocations = refs.SelectMany(r => r.Locations).ToList();
        allLocations.Should().ContainSingle();

        var refLoc = allLocations[0];
        var mapped = refLoc.Location.GetMappedLineSpan();
        mapped.HasMappedPath.Should().BeTrue();
        mapped.Path.Should().Be(@"C:\Repo\Pages\Component.razor");
        mapped.StartLinePosition.Line.Should().Be(4); // 0-indexed for line 5

        // Now test resolving symbol from the mapped razor location (line 5, column 15)
        var genDoc = solution.GetDocument(genDocInfo.Id)!;
        var genTree = (await genDoc.GetSyntaxTreeAsync())!;
        var genRoot = await genTree.GetRootAsync();
        var targetLine = 4; // line 5

        var targetCol = 20; // 0-indexed column inside 'TargetMethod' (which is [18-30])

        var token = genRoot.DescendantTokens().FirstOrDefault(t =>
        {
            var m = t.GetLocation().GetMappedLineSpan();
            return m.HasMappedPath &&
                   string.Equals(m.Path, @"C:\Repo\Pages\Component.razor", StringComparison.OrdinalIgnoreCase) &&
                   m.StartLinePosition.Line <= targetLine &&
                   m.EndLinePosition.Line >= targetLine &&
                   (m.StartLinePosition.Line < targetLine || m.StartLinePosition.Character <= targetCol) &&
                   (m.EndLinePosition.Line > targetLine || m.EndLinePosition.Character >= targetCol);
        });

        token.Should().NotBeNull();
        token.Text.Should().Be("TargetMethod");

        var semModel = comp.GetSemanticModel(genTree);
        var sym = semModel.GetSymbolInfo(token.Parent!).Symbol;
        sym.Should().NotBeNull();
        sym.Should().Be(targetMethod);
    }

